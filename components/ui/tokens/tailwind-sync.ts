/**
 * Token Sync Script
 *
 * Reads design-tokens.json and generates Tailwind theme config.
 * Run: npx tsx components/ui/tokens/tailwind-sync.ts
 *
 * This script ensures the website's Tailwind config stays in sync
 * with the UI kit's design tokens.
 */

import fs from 'fs'
import path from 'path'

interface DesignTokens {
  version: string
  lastUpdated: string
  colors: {
    brand: Record<string, string>
    accent: Record<string, string>
    neutral: Record<string, string>
    semantic: Record<string, string>
  }
  typography: {
    fontFamily: string
    fontWeights: Record<string, number>
    scale: Record<string, string>
    lineHeight: Record<string, number>
    letterSpacing: Record<string, string>
    styles: Record<string, object>
  }
  spacing: Record<string, string>
  radius: Record<string, string>
  shadows: Record<string, string>
  transitions: {
    easing: Record<string, string>
    duration: Record<string, string>
  }
  components: object
  logo: object
}

function generateTailwindConfig(tokens: DesignTokens): string {
  const timestamp = new Date().toISOString()

  return `// AUTO-GENERATED by tailwind-sync.ts - DO NOT EDIT MANUALLY
// Source: global-resources/brand-assets/ui-kit/design-tokens.json
// Version: ${tokens.version}
// Last synced: ${timestamp}

import type { Config } from 'tailwindcss'

export const designSystemTheme: NonNullable<Config['theme']>['extend'] = {
  colors: {
    brand: {
      primary: '${tokens.colors.brand.primary}',
      'primary-dark': '${tokens.colors.brand.primaryDark}',
      'primary-light': '${tokens.colors.brand.primaryLight}',
      'primary-subtle': '${tokens.colors.brand.primarySubtle}',
    },
    accent: {
      slate: '${tokens.colors.accent.slate}',
      'slate-light': '${tokens.colors.accent.slateLight}',
      'slate-subtle': '${tokens.colors.accent.slateSubtle}',
    },
    neutral: {
      '950': '${tokens.colors.neutral['950']}',
      '900': '${tokens.colors.neutral['900']}',
      '800': '${tokens.colors.neutral['800']}',
      '700': '${tokens.colors.neutral['700']}',
      '600': '${tokens.colors.neutral['600']}',
      '500': '${tokens.colors.neutral['500']}',
      '400': '${tokens.colors.neutral['400']}',
      '300': '${tokens.colors.neutral['300']}',
      '200': '${tokens.colors.neutral['200']}',
      '100': '${tokens.colors.neutral['100']}',
      '50': '${tokens.colors.neutral['50']}',
      white: '${tokens.colors.neutral.white}',
    },
    semantic: {
      success: '${tokens.colors.semantic.success}',
      'success-light': '${tokens.colors.semantic.successLight}',
      warning: '${tokens.colors.semantic.warning}',
      'warning-light': '${tokens.colors.semantic.warningLight}',
      error: '${tokens.colors.semantic.error}',
      'error-light': '${tokens.colors.semantic.errorLight}',
      info: '${tokens.colors.semantic.info}',
      'info-light': '${tokens.colors.semantic.infoLight}',
    },
  },
  fontFamily: {
    manrope: ['Manrope', '-apple-system', 'BlinkMacSystemFont', 'sans-serif'],
  },
  fontSize: {
    xs: '${tokens.typography.scale.xs}',
    sm: '${tokens.typography.scale.sm}',
    base: '${tokens.typography.scale.base}',
    lg: '${tokens.typography.scale.lg}',
    xl: '${tokens.typography.scale.xl}',
    '2xl': '${tokens.typography.scale['2xl']}',
    '3xl': '${tokens.typography.scale['3xl']}',
    '4xl': '${tokens.typography.scale['4xl']}',
    '5xl': '${tokens.typography.scale['5xl']}',
    '6xl': '${tokens.typography.scale['6xl']}',
    '7xl': '${tokens.typography.scale['7xl']}',
  },
  lineHeight: {
    none: '${tokens.typography.lineHeight.none}',
    tight: '${tokens.typography.lineHeight.tight}',
    snug: '${tokens.typography.lineHeight.snug}',
    normal: '${tokens.typography.lineHeight.normal}',
    relaxed: '${tokens.typography.lineHeight.relaxed}',
  },
  letterSpacing: {
    tight: '${tokens.typography.letterSpacing.tight}',
    widest: '${tokens.typography.letterSpacing.widest}',
    logo: '${tokens.typography.letterSpacing.logo}',
  },
  borderRadius: {
    sm: '${tokens.radius.sm}',
    md: '${tokens.radius.md}',
    lg: '${tokens.radius.lg}',
    xl: '${tokens.radius.xl}',
    full: '${tokens.radius.full}',
  },
  boxShadow: {
    sm: '${tokens.shadows.sm}',
    md: '${tokens.shadows.md}',
    lg: '${tokens.shadows.lg}',
    xl: '${tokens.shadows.xl}',
    card: '${tokens.shadows.card}',
    'card-hover': '${tokens.shadows.cardHover}',
    'card-float': '${tokens.shadows.cardFloat}',
  },
  transitionTimingFunction: {
    smooth: '${tokens.transitions.easing.smooth}',
    spring: '${tokens.transitions.easing.spring}',
  },
  transitionDuration: {
    fast: '${tokens.transitions.duration.fast}',
    base: '${tokens.transitions.duration.base}',
    slow: '${tokens.transitions.duration.slow}',
    entrance: '${tokens.transitions.duration.entrance}',
  },
}

export default designSystemTheme
`
}

// Main execution
const scriptDir = path.dirname(new URL(import.meta.url).pathname)
// Handle Windows path (remove leading slash if present)
const normalizedScriptDir = scriptDir.startsWith('/') && scriptDir.includes(':')
  ? scriptDir.slice(1)
  : scriptDir

const tokensPath = path.resolve(normalizedScriptDir, '../../../../../global-resources/brand-assets/ui-kit/design-tokens.json')
const outputPath = path.resolve(normalizedScriptDir, './generated-theme.ts')

console.log('Reading tokens from:', tokensPath)
console.log('Writing theme to:', outputPath)

try {
  const tokensContent = fs.readFileSync(tokensPath, 'utf-8')
  const tokens: DesignTokens = JSON.parse(tokensContent)
  const output = generateTailwindConfig(tokens)
  fs.writeFileSync(outputPath, output)
  console.log(`✓ Generated theme from design-tokens.json v${tokens.version}`)
} catch (error) {
  console.error('Error syncing tokens:', error)
  process.exit(1)
}
